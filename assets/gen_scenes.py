#!/usr/bin/env python3
"""Generate Pioneer Trail's non-title pixel scenes from deterministic geometry.

The title is generated separately. This script reuses its canonical wagon and
ox shapes and owns all non-title terrain, actors, landmarks, and minigame assets.
"""

from __future__ import annotations

import argparse
from pathlib import Path

from gen_logo import OX, WAGON, sprite


ROOT = Path(__file__).resolve().parents[1]
ART = ROOT / "crates" / "data" / "art"
PALETTE = {"K": "#000000", "W": "#FFFFFF", "G": "#1BCB01", "V": "#E434FE", "O": "#F26A00", "B": "#1B9AFE"}


class Canvas:
    def __init__(self, width: int = 80, height: int = 32) -> None:
        self.width, self.height = width, height
        self.rows = [["." for _ in range(width)] for _ in range(height)]

    def put(self, x: int, y: int, color: str) -> None:
        if 0 <= x < self.width and 0 <= y < self.height:
            self.rows[y][x] = color

    def rect(self, x: int, y: int, width: int, height: int, color: str) -> None:
        for yy in range(y, y + height):
            for xx in range(x, x + width):
                self.put(xx, yy, color)

    def line(self, x0: int, y0: int, x1: int, y1: int, color: str) -> None:
        dx, sx = abs(x1 - x0), 1 if x0 < x1 else -1
        dy, sy = -abs(y1 - y0), 1 if y0 < y1 else -1
        error = dx + dy
        while True:
            self.put(x0, y0, color)
            if (x0, y0) == (x1, y1):
                return
            twice = 2 * error
            if twice >= dy:
                error += dy
                x0 += sx
            if twice <= dx:
                error += dx
                y0 += sy

    def polygon(self, points: list[tuple[int, int]], color: str) -> None:
        min_y = max(0, min(y for _, y in points))
        max_y = min(self.height - 1, max(y for _, y in points))
        for y in range(min_y, max_y + 1):
            intersections = []
            for (x1, y1), (x2, y2) in zip(points, points[1:] + points[:1]):
                if (y1 <= y < y2) or (y2 <= y < y1):
                    intersections.append(x1 + (y - y1) * (x2 - x1) / (y2 - y1))
            intersections.sort()
            for left, right in zip(intersections[::2], intersections[1::2]):
                for x in range(round(left), round(right) + 1):
                    self.put(x, y, color)

    def ellipse(self, cx: int, cy: int, rx: int, ry: int, color: str) -> None:
        for y in range(cy - ry, cy + ry + 1):
            for x in range(cx - rx, cx + rx + 1):
                if (x - cx) ** 2 * ry ** 2 + (y - cy) ** 2 * rx ** 2 <= rx ** 2 * ry ** 2:
                    self.put(x, y, color)

    def save(self, name: str) -> None:
        lines = ["# Generated by assets/gen_scenes.py. Do not hand-edit."]
        lines.extend("".join(row) for row in self.rows)
        (ART / name).write_text("\n".join(lines) + "\n")

    def blit(self, art: list[str], x0: int = 0, y0: int = 0) -> None:
        for y, row in enumerate(art):
            for x, pixel in enumerate(row):
                self.put(x0 + x, y0 + y, pixel)


def ground(c: Canvas, color: str = "G") -> None:
    c.rect(0, 30, 80, 1, color)
    for x in range(80):
        c.put(x, 31, color if x % 5 else "K")


def sky_band(c: Canvas, color: str, y: int = 5, width: int = 2) -> None:
    c.rect(0, y, 80, width, color)
    for x in range(0, 80, 9):
        c.put(x, y + width - 1, ".")


def pine(c: Canvas, x: int, base: int, height: int) -> None:
    for level, y in enumerate(range(base - height, base, 3)):
        half = 1 + level // 2
        c.polygon([(x, y), (x - half - 2, y + 4), (x + half + 2, y + 4)], "G")
    c.rect(x, base, 1, 2, "O")


def mountain(c: Canvas, x: int, peak: int, base: int, half: int, color: str = "B") -> None:
    c.polygon([(x - half, base), (x, peak), (x + half, base)], color)
    cap = max(2, half // 3)
    c.polygon([(x, peak), (x - cap, peak + cap + 2), (x, peak + cap), (x + cap, peak + cap + 2)], "W")


def terrain() -> None:
    c = Canvas(); sky_band(c, "B", 7, 2)
    for x in range(4, 80, 11):
        c.line(x, 27, x + 2, 24, "G")
        c.line(x + 2, 24, x + 4, 27, "G")
    ground(c); c.save("terrain_plains.px")

    c = Canvas(); sky_band(c, "V", 6, 2)
    c.polygon([(0, 28), (0, 20), (13, 16), (28, 22), (44, 15), (60, 20), (80, 14), (80, 28)], "G")
    for x in range(5, 80, 13): c.rect(x, 23 - (x % 3), 2, 2, "G")
    ground(c); c.save("terrain_hills.px")

    c = Canvas(); sky_band(c, "B", 4, 2)
    mountain(c, 13, 10, 30, 17); mountain(c, 39, 5, 30, 23); mountain(c, 66, 11, 30, 19)
    for x in range(4, 80, 12): pine(c, x, 29, 7 + x % 4)
    ground(c); c.save("terrain_mountains.px")

    c = Canvas(); sky_band(c, "V", 5, 2)
    c.polygon([(0, 29), (0, 23), (20, 19), (38, 23), (58, 18), (80, 22), (80, 29)], "O")
    for x in range(7, 80, 15): c.ellipse(x, 26, 4, 1, "O")
    ground(c, "O"); c.save("terrain_desert.px")

    c = Canvas(); sky_band(c, "B", 6, 2)
    for x, h in [(5, 13), (14, 10), (24, 16), (36, 11), (47, 15), (59, 12), (70, 17), (78, 10)]: pine(c, x, 29, h)
    ground(c); c.save("terrain_forest.px")

    c = Canvas(); sky_band(c, "B", 5, 2)
    c.polygon([(0, 29), (0, 18), (15, 14), (29, 19), (44, 13), (60, 19), (80, 15), (80, 29)], "G")
    c.polygon([(30, 30), (38, 21), (48, 16), (54, 12), (62, 8), (68, 7), (68, 30)], "B")
    for y in range(11, 30, 5): c.line(50 + y // 3, y, 63 + y // 4, y + 1, "W")
    ground(c); c.save("terrain_river_valley.px")


def river_scene(name: str, shift: int, bank: str = "G") -> None:
    c = Canvas(); sky_band(c, "B", 5, 2)
    c.rect(0, 7, 80, 23, bank)
    points = [(shift + 25, 30), (shift + 7, 24), (shift + 26, 18), (shift + 47, 12), (shift + 33, 7), (shift + 55, 7), (shift + 68, 13), (shift + 48, 20), (shift + 30, 26), (shift + 45, 30)]
    c.polygon(points, "B")
    for y in range(10, 29, 4):
        x = (shift + 34 + y * 3) % 60 + 10
        c.line(x, y, min(78, x + 9), y + 1, "W")
        c.put(min(79, x + 9), y, "W")
    for x in range(4, 80, 15):
        c.rect(x, 26, 2, 3, "O")
        c.polygon([(x + 1, 18), (x - 3, 26), (x + 5, 26)], "G")
    ground(c, bank); c.save(name)


def forts() -> None:
    specs = [("fort_kearney.px", 10, 51, 18), ("fort_laramie.px", 7, 59, 14), ("fort_bridger.px", 13, 54, 16), ("fort_hall.px", 9, 57, 17), ("fort_boise.px", 15, 49, 15), ("fort_walla_walla.px", 8, 61, 13)]
    for name, left, right, tower in specs:
        c = Canvas(); sky_band(c, "B", 5, 2)
        c.rect(left, 18, right - left, 11, "O")
        # Corner bastions and alternating palisade tips make every fort read as defended.
        c.polygon([(left - 5, 29), (left, 14), (left + 5, 29)], "O")
        c.polygon([(right - 5, 29), (right, 14), (right + 5, 29)], "O")
        for x in range(left, right, 3):
            c.polygon([(x, 18), (x + 1, 15), (x + 2, 18)], "W")
        gate = (left + right) // 2
        c.rect(gate - 4, 22, 9, 7, "W"); c.rect(gate - 2, 25, 5, 4, "O")
        c.rect(tower, 8, 2, 10, "O"); c.line(tower + 2, 8, tower + 8, 10, "W"); c.rect(tower + 7, 10, 5, 3, "B")
        for x in range(left + 7, right - 5, 11): c.rect(x, 21, 3, 3, "W")
        ground(c); c.save(name)


