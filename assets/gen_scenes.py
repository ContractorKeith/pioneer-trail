def map_oregon() -> None:
    c = Canvas(); c.rect(0, 0, 80, 32, "K")
    # Rivers frame a clear westward route across the map.
    c.line(9, 0, 14, 31, "B"); c.line(58, 0, 63, 31, "B"); c.line(0, 25, 80, 19, "B")
    route = [(8, 27), (16, 25), (22, 23), (31, 22), (39, 19), (46, 17), (51, 13), (57, 11), (65, 9), (72, 6)]
    for a, b in zip(route, route[1:]): c.line(*a, *b, "W")
    for x, y in route: c.ellipse(x, y, 1, 1, "O")
    c.ellipse(46, 17, 2, 2, "G"); c.save("map_oregon.px")


def animal(c: Canvas, kind: str, step: int) -> None:
    # Each profile uses a deliberately different outline, not a shared body rectangle.
    if kind == "buffalo":
        c.polygon([(1, 6), (3, 3), (5, 2), (7, 4), (10, 4), (12, 5), (14, 5), (15, 7), (13, 8), (4, 8)], "O")
        c.rect(2, 5, 2, 3, "O"); c.put(1, 4, "W"); c.put(3, 3, "W"); c.put(12, 5, "W")
        legs = [(4, 8), (7, 8), (11, 8), (13, 8)]
    elif kind == "bear":
        c.ellipse(7, 6, 6, 3, "O"); c.ellipse(12, 6, 3, 2, "O"); c.put(11, 3, "O"); c.put(13, 4, "W"); c.put(15, 6, "K")
        legs = [(3, 8), (6, 8), (10, 8), (13, 8)]
    elif kind == "deer":
        c.polygon([(2, 7), (4, 4), (9, 4), (11, 5), (12, 3), (14, 2), (15, 4), (13, 6), (11, 7), (5, 8)], "O")
        c.put(14, 1, "W"); c.put(12, 2, "W"); c.put(15, 5, "W")
        legs = [(4, 8), (7, 8), (10, 8), (12, 8)]
    elif kind == "rabbit":
        c.ellipse(8, 7, 5, 2, "O"); c.ellipse(12, 5, 2, 2, "O"); c.rect(11, 0, 1, 4, "W"); c.rect(13, 0, 1, 4, "W"); c.put(14, 5, "W")
        legs = [(6, 8), (9, 8)]
    else:
        c.ellipse(8, 6, 4, 3, "O"); c.ellipse(12, 6, 2, 2, "O"); c.polygon([(4, 7), (0, 3), (1, 0), (4, 2), (6, 5)], "O")
        c.put(13, 5, "W"); legs = [(7, 8), (10, 8)]
    for index, (x, y) in enumerate(legs):
        c.put(x + ((index + step) % 2), y, "K")
        c.put(x + ((index + step) % 2), 9, "K")


def hunting() -> None:
    for kind in ["buffalo", "bear", "deer", "rabbit", "squirrel"]:
        for step in range(2):
            c = Canvas(16, 10); animal(c, kind, step); c.save(f"{kind}_{step}.px")
    for step in range(2):
        c = Canvas(13, 11)
        c.line(0, 5, 4, 5, "W"); c.line(8, 5, 12, 5, "W"); c.line(6, 0, 6, 3, "W"); c.line(6, 7, 6, 10, "W")
        c.ellipse(6, 5, 2 + step, 2 + step, "O"); c.put(6, 5, "W"); c.save(f"crosshair_{step}.px")


def actors() -> None:
    """Turn the canonical logo actors into independently animated sprites."""
    wagon = sprite(WAGON)
    ox = sprite(OX)
    wheel_centers = (6, 33)
    for frame in range(4):
        c = Canvas(40, 20)
        c.blit(wagon)
        # Keep the full canonical wagon silhouette. Alternate a plus and an X
        # inside each white rim; the canopy's center rib shifts one pixel to
        # give the body a restrained trail bob without changing its footprint.
        for center in wheel_centers:
            if frame % 2 == 0:
                for x, y in [(center, 13), (center, 14), (center, 15), (center - 1, 15), (center + 1, 15), (center, 16), (center, 17)]:
                    c.put(x, y, "K")
            else:
                for x, y in [(center - 1, 14), (center + 1, 14), (center, 15), (center - 1, 16), (center + 1, 16)]:
                    c.put(x, y, "K")
        rib_x = 19 + (1 if frame in (1, 2) else 0)
        for y in range(4, 8):
            c.put(rib_x, y, "K")
        c.save(f"wagon_{frame}.px")

    for frame in range(2):
        c = Canvas(20, 10)
        c.blit(ox)
        # Original horns and body stay intact; only the four hooves trade
        # forward/back positions for a walking cycle.
        for x in range(20):
            if c.rows[9][x] == "K":
                c.put(x, 9, ".")
        hooves = (3, 4, 7, 8, 14, 15, 18, 19) if frame == 0 else (4, 5, 7, 8, 13, 14, 17, 18)
        for x in hooves:
            c.put(x, 9, "K")
        c.save(f"ox_{frame}.px")


def rafting() -> None:
    c = Canvas(12, 6); c.polygon([(1, 3), (3, 1), (9, 1), (11, 3), (9, 5), (3, 5)], "O")
    c.rect(3, 2, 6, 2, "W"); c.line(1, 0, 10, 5, "K"); c.save("raft.px")
    for index, points in enumerate([[(0, 3), (2, 0), (5, 3)], [(0, 3), (3, 0), (5, 3)], [(0, 3), (2, 1), (5, 3)]]):
        c = Canvas(6, 4); c.polygon(points + [(5, 3), (0, 3)], "W"); c.put(2 + index % 2, 2, "B"); c.save(f"rock_{index}.px")
    c = Canvas(8, 10)
    for y, row in enumerate(["........", "...WW...", "..WWWW..", ".WWWWWW.", ".WWKWWW.", ".WKKKWW.", ".WWKWWW.", ".WWWWWW.", ".WWWWWW.", "WWWWWWWW"]):
        for x, pixel in enumerate(row): c.put(x, y, pixel)
    c.save("tombstone.px")


def generate() -> None:
    terrain()
    for name, shift, bank in [("kansas_river.px", 0, "G"), ("big_blue.px", 8, "G"), ("green_river.px", 15, "G"), ("snake_river.px", 23, "O"), ("columbia.px", 31, "O")]:
        river_scene(name, shift, bank)
    forts(); landmarks(); map_oregon(); hunting(); actors(); rafting()


def contact_sheet(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    assets = sorted(ART.glob("*.px"))
    cell_w, cell_h, scene_scale, columns = 184, 94, 2, 4
    rows = (len(assets) + columns - 1) // columns
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{cell_w * columns}" height="{cell_h * rows}" viewBox="0 0 {cell_w * columns} {cell_h * rows}">', '<rect width="100%" height="100%" fill="#000000"/>']
    for index, asset in enumerate(assets):
        x0, y0 = (index % columns) * cell_w, (index // columns) * cell_h
        rows_px = [line for line in asset.read_text().splitlines() if not line.startswith("#")]
        scale = scene_scale if len(rows_px[0]) >= 40 else 6
        out.append(f'<text x="{x0 + 4}" y="{y0 + 11}" fill="#fff" font-family="monospace" font-size="9">{asset.stem}</text>')
        for y, row in enumerate(rows_px):
            for x, pixel in enumerate(row):
                if pixel != ".":
                    out.append(f'<rect x="{x0 + 4 + x * scale}" y="{y0 + 15 + y * scale}" width="{scale}" height="{scale}" fill="{PALETTE[pixel]}"/>')
    out.append("</svg>")
    path.write_text("\n".join(out))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--contact-sheet", type=Path)
    args = parser.parse_args()
    generate()
    if args.contact_sheet:
        contact_sheet(args.contact_sheet)
